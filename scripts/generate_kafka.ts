import { fromAvro, type AvroSchema } from '@afcms/avro-zod';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { format, resolveConfig } from 'prettier';
import ts from 'typescript';

const defaultInput = fileURLToPath(new URL('../src/app/kafka/defs/', import.meta.url));

interface GenerateOptions {
  input?: string;
  output?: string;
  check?: boolean;
}

async function schemaFiles(directory: string): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await schemaFiles(path)));
    else if (entry.isFile() && /\.(json|avsc)$/.test(entry.name)) files.push(path);
  }
  return files.sort();
}

async function existingContent(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

function updateSchema(content: string, path: string, name: string, declaration: string): string {
  const module = ts.createSourceFile(path, content, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const statements = module.statements.filter(
    (statement): statement is ts.VariableStatement =>
      ts.isVariableStatement(statement) &&
      statement.declarationList.declarations.some(
        ({ name: identifier }) => ts.isIdentifier(identifier) && identifier.text === `${name}Avro`,
      ),
  );
  const statement = statements[0];
  if (
    statements.length !== 1 ||
    !statement ||
    statement.declarationList.declarations.length !== 1
  ) {
    throw new Error(
      `${path}: expected a single ${name}Avro variable declaration; refusing to overwrite hand-edited code.`,
    );
  }
  // Keep everything outside the Avro declaration byte-for-byte, including manual formatting.
  return (
    content.slice(0, statement.getStart(module)) +
    declaration.trimEnd() +
    content.slice(statement.getEnd())
  );
}

/** Validate every input before replacing any generated modules. */
export async function generateKafka({
  input = defaultInput,
  output = input,
  check = false,
}: GenerateOptions = {}) {
  input = resolve(input);
  output = resolve(output);
  const files = await schemaFiles(input);
  if (files.length === 0) throw new Error(`No .json or .avsc schemas found in ${input}.`);

  const modules = new Map<string, string>();
  const registryPath = join(output, 'registry.ts');
  const topics = new Map<string, string>();
  for (const file of files) {
    const name = basename(file, extname(file));
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
      throw new Error(`${file}: filename must be a TypeScript identifier, such as MyTopic.json.`);
    }
    const path = join(output, relative(input, file)).replace(/\.(json|avsc)$/, '.ts');
    if (modules.has(path)) throw new Error(`Multiple schemas would generate ${path}.`);
    if (path === registryPath)
      throw new Error(`${file}: registry.ts is reserved for the schema registry.`);
    if (topics.has(name))
      throw new Error(`${file}: duplicate topic name ${name} in the schema registry.`);
    topics.set(name, path);

    try {
      const source: unknown = JSON.parse(await readFile(file, 'utf8'));
      // fromAvro validates runtime input; the emitted literal supplies static inference.
      fromAvro(source as AvroSchema);
      const options = { ...(await resolveConfig(path)), parser: 'typescript' };
      const declaration = await format(
        `export const ${name}Avro = ${JSON.stringify(source, null, 2)} as const satisfies AvroSchema;`,
        options,
      );
      const existing = await existingContent(path);
      if (existing !== undefined) {
        modules.set(path, updateSchema(existing, path, name, declaration));
        continue;
      }
      const module = `// Only the ${name}Avro declaration is generated by scripts/generate_kafka.ts.
// Source: ${JSON.stringify(relative(input, file).split('\\').join('/'))}
import { fromAvro, type AvroSchema } from '@afcms/avro-zod';
import type { output } from 'zod/v4/core';

${declaration}
export const ${name}Schema = fromAvro(${name}Avro);
export type ${name} = output<typeof ${name}Schema>;

// Edit these factories by hand. Each is evaluated for every send, including presets.
export const ${name}GeneratedParameters = {} satisfies {
  [K in keyof ${name}]?: () => ${name}[K];
};
`;
      modules.set(path, await format(module, options));
    } catch (error) {
      throw new Error(`${file}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }

  const imports = [...topics].map(([name, path]) => {
    const specifier = `./${relative(output, path).split('\\').join('/').replace(/\.ts$/, '.js')}`;
    return `import { ${name}Schema } from ${JSON.stringify(specifier)};`;
  });
  const entries = [...topics.keys()].map(
    (name) => `  ${name === '__proto__' ? "['__proto__']" : name}: ${name}Schema,`,
  );
  modules.set(
    registryPath,
    await format(
      `// Generated by scripts/generate_kafka.ts. Do not edit.
${imports.join('\n')}

export const registry = {
${entries.join('\n')}
} as const;
`,
      { ...(await resolveConfig(registryPath)), parser: 'typescript' },
    ),
  );

  const changed: string[] = [];
  for (const [path, content] of modules) {
    if ((await existingContent(path)) !== content) changed.push(path);
  }
  if (check && changed.length) {
    throw new Error(
      `Generated topics are missing or out of date:\n${changed.join('\n')}\nRun the generator without --check.`,
    );
  }
  if (!check) {
    for (const path of changed) {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, modules.get(path)!, 'utf8');
    }
  }
  return { total: topics.size, updated: check ? 0 : changed.length };
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      input: { type: 'string' },
      output: { type: 'string' },
      check: { type: 'boolean', default: false },
      help: { type: 'boolean', short: 'h' },
    },
  });
  if (values.help) {
    console.log(
      'Usage: node scripts/generate_kafka.ts [--input directory] [--output directory] [--check]\nDefaults: read src/app/kafka/defs recursively, write .ts modules beside each schema, and generate registry.ts in the output directory.',
    );
    return;
  }
  const result = await generateKafka(values);
  console.log(
    values.check
      ? `Checked ${result.total} topic module(s) and registry.`
      : `Generated ${result.total} topic module(s) and registry, ${result.updated} file(s) updated.`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
